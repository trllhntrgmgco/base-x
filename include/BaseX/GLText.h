static int charIndex(char c) {
    if (c >= ' ' && c <= 'z') return c - ' ';
    return 0;
}

inline void draw(const char* text, float x, float y, float scale = 1.5f) {
    float px = x;
    float pw = scale;
    for (const char* p = text; *p; p++) {
        int idx = charIndex(*p >= 'a' ? *p : (*p >= 'A' && *p <= 'Z') ? (*p - 'A' + 'a') : *p);
        if (*p >= 'A' && *p <= 'Z') idx = *p - 'A' + ('A' - ' ');
        else idx = charIndex(*p);
        const unsigned char* glyph = FONT[idx];
        for (int row = 0; row < 7; row++) {
            for (int col = 0; col < 5; col++) {
                if (glyph[row] & (1 << (4 - col))) {
                    float gx = px + col * pw;
                    float gy = y + (6 - row) * pw;
                    glBegin(GL_QUADS);
                    glVertex2f(gx, gy);
                    glVertex2f(gx + pw, gy);
                    glVertex2f(gx + pw, gy + pw);
                    glVertex2f(gx, gy + pw);
                    glEnd();
                }
            }
        }
        px += 6 * pw;
    }
}

inline float textWidth(const char* text, float scale = 1.5f) {
    return (float)strlen(text) * 6.0f * scale;
}

inline void drawRight(const char* text, float rightX, float y, float scale = 1.5f) {
    draw(text, rightX - textWidth(text, scale), y, scale);
}

inline void drawCentered(const char* text, float cx, float y, float scale = 1.5f) {
    draw(text, cx - textWidth(text, scale) * 0.5f, y, scale);
}

